export function interpolate(template, values = {}) {
  return String(template).replace(/\{\{(\w+)\}\}/g, (_match, key) => values[key] ?? "");
}

export function isSupportedLanguage(language) {
  return SUPPORTED_CODES.has(language);
}

export function getLanguageDirection(language) {
  return RTL_LANGUAGES.has(language) ? "rtl" : "ltr";
}

export function getLanguagePath(language) {
  const segment = LANGUAGE_ROUTE_SEGMENTS[language];
  return segment ? `/${segment}/` : "/";
}

export function getLanguageFromPathname(pathname = "") {
  const [segment] = String(pathname)
    .split(/[?#]/)[0]
    .split("/")
    .filter(Boolean);

  return ROUTE_SEGMENT_TO_LANGUAGE[String(segment || "").toLowerCase()] || null;
}

export function detectLanguage(languages) {
  const preferences = Array.isArray(languages) ? languages : languages ? [languages] : [];

  for (const preference of preferences) {
    const normalized = String(preference || "").toLowerCase();
    if (normalized.startsWith("zh-hant")) {
      return "zh-Hant";
    }
    const alias = LANGUAGE_ALIASES[normalized];
    const baseCode = alias || normalized.split("-")[0];

    if (isSupportedLanguage(baseCode)) {
      return baseCode;
    }
  }

  return DEFAULT_LANGUAGE;
}

export function getInitialLanguage(environment = {}) {
  const storage = environment.localStorage ?? globalThis.localStorage;
  const navigatorSource = environment.navigator ?? globalThis.navigator;
  const locationSource = environment.location ?? globalThis.location;
  const routeLanguage = getLanguageFromPathname(locationSource?.pathname);

  if (routeLanguage) {
    return routeLanguage;
  }

  try {
    const stored = storage?.getItem("beats-your-music-language");
    if (isSupportedLanguage(stored)) {
      return stored;
    }
  } catch {
    // Local storage can be disabled in private or embedded contexts.
  }

  return detectLanguage(navigatorSource?.languages || navigatorSource?.language);
}

export function createTranslator(language) {
  const selectedLanguage = isSupportedLanguage(language) ? language : DEFAULT_LANGUAGE;
  const selectedTranslations = translations[selectedLanguage];

  return function translate(key, values = {}) {
    const template = selectedTranslations[key] ?? translations[DEFAULT_LANGUAGE][key] ?? key;
    return interpolate(template, values);
  };
}
